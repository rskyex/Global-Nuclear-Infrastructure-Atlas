// Computes conflict exposure for every plant from the committed UCDP extract
// (data/ucdp/ucdp-extract.csv, made by scripts/extract-ucdp.py) and writes
// src/data/generated/conflictExposure.js. Run with `npm run gen:conflict`.
//
// Rule: a plant is exposed when, within RADIUS_KM of its coordinates and inside
// the extract window, UCDP records at least MIN_EVENTS events or at least
// MIN_FATALITIES best-estimate fatalities.
import { readFileSync, writeFileSync } from 'node:fs';
import { createServer } from 'vite';

export const RADIUS_KM = 100;
export const MIN_EVENTS = 5;
export const MIN_FATALITIES = 25;

const root = new URL('..', import.meta.url);
const meta = JSON.parse(readFileSync(new URL('data/ucdp/extract-meta.json', root), 'utf8'));

// Minimal CSV parser (quoted fields, doubled quotes) for the extract we write ourselves.
function parseCsv(text) {
  const rows = [];
  let row = [], field = '', q = false;
  for (let i = 0; i < text.length; i++) {
    const ch = text[i];
    if (q) {
      if (ch === '"' && text[i + 1] === '"') { field += '"'; i++; }
      else if (ch === '"') q = false;
      else field += ch;
    } else if (ch === '"') q = true;
    else if (ch === ',') { row.push(field); field = ''; }
    else if (ch === '\n') { row.push(field); rows.push(row); row = []; field = ''; }
    else if (ch !== '\r') field += ch;
  }
  if (field || row.length) { row.push(field); rows.push(row); }
  const [head, ...body] = rows;
  return body.map((r) => Object.fromEntries(head.map((h, i) => [h, r[i]])));
}

const km = (aLat, aLng, bLat, bLng) => {
  const p = Math.PI / 180;
  const h = Math.sin(((bLat - aLat) * p) / 2) ** 2 + Math.cos(aLat * p) * Math.cos(bLat * p) * Math.sin(((bLng - aLng) * p) / 2) ** 2;
  return 12742 * Math.asin(Math.sqrt(h));
};

const events = parseCsv(readFileSync(new URL('data/ucdp/ucdp-extract.csv', root), 'utf8')).map((e) => ({
  ...e, lat: Number(e.latitude), lng: Number(e.longitude), best: Number(e.best) || 0,
}));

const server = await createServer({
  configFile: false, appType: 'custom', logLevel: 'silent',
  optimizeDeps: { noDiscovery: true, include: [] },
  server: { middlewareMode: true, hmr: false, ws: false },
});
let plants;
try {
  ({ commercialPlants: plants } = await server.ssrLoadModule('/src/data/commercialPlants.js'));
} finally {
  await server.close();
}

const byPlant = {};
for (const p of plants) {
  const near = events.filter((e) => km(p.lat, p.lng, e.lat, e.lng) <= RADIUS_KM);
  const fatalities = near.reduce((s, e) => s + e.best, 0);
  if (!near.length) continue;
  byPlant[p.id] = {
    events: near.length,
    fatalities,
    exposed: near.length >= MIN_EVENTS || fatalities >= MIN_FATALITIES,
    // UCDP type_of_violence: 1 state-based, 2 non-state, 3 one-sided
    byType: {
      stateBased: near.filter((e) => e.type_of_violence === '1').length,
      nonState: near.filter((e) => e.type_of_violence === '2').length,
      oneSided: near.filter((e) => e.type_of_violence === '3').length,
    },
    conflicts: [...new Set(near.map((e) => e.conflict_name))].slice(0, 5),
  };
}

const out = `// Generated by scripts/gen-conflict-exposure.mjs from data/ucdp/ucdp-extract.csv. Do not edit.
// UCDP data (CC BY 4.0): ${meta.sources.map((s) => s.name).join('; ')}.
export const conflictRule = ${JSON.stringify({ radiusKm: RADIUS_KM, minEvents: MIN_EVENTS, minFatalities: MIN_FATALITIES, ...meta }, null, 2)};

// Plants with at least one UCDP event within ${RADIUS_KM} km in the window.
export const conflictByPlant = ${JSON.stringify(byPlant, null, 2)};
`;
writeFileSync(new URL('src/data/generated/conflictExposure.js', root), out);
const exposed = Object.entries(byPlant).filter(([, v]) => v.exposed);
console.log(`window ${meta.windowStart}..${meta.windowEnd}; ${Object.keys(byPlant).length} plants with events within ${RADIUS_KM} km; exposed:`);
for (const [id, v] of exposed) console.log(`  ${id}: ${v.events} events, ${v.fatalities} deaths, types ${JSON.stringify(v.byType)}; ${v.conflicts.join(' / ')}`);
